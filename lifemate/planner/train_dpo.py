"""LoRA DPO fine-tuning script for the LifeMate Qwen 3.8 4B Planner.

Designed to consume the preference dataset generated by scripts/build_dpo_dataset.py
(Stage 1 programmatic) or scripts/sample_onpolicy_dpo.py (Stage 2 on-policy rollouts)
in optimize/dpo/dataset/ without modifying system prompts or tool schemas.

Default model: Ma7ee7/Qwen3.8_4B_Distilled (override with --model or QWEN_MODEL_PATH).
Examples:
    python -m lifemate.planner.train_dpo --model Ma7ee7/Qwen3.8_4B_Distilled
    python -m lifemate.planner.train_dpo --model Ma7ee7/Qwen3.8_4B_Distilled --load-in-4bit
    python -m lifemate.planner.train_dpo --model Qwen/Qwen3-4B-Instruct-2507 --wrap-think

Smoke test data loading & stats without a GPU:
    python -m lifemate.planner.train_dpo --dry-run

Then run end-to-end evaluation with the trained LoRA adapter:
    python -m lifemate.planner.runner --root data --split train --ids eval/splits/dev_ids.txt \\
        --prompt prompts/gepa/vuong/planner_v15.txt --llm Ma7ee7/Qwen3.8_4B_Distilled \\
        --llm-lora checkpoints/planner_dpo_qwen38_lora --mapper none --text \\
        --verify-rounds 0 --out runs/dev_dpo.jsonl
    python eval/scorer.py --sub runs/dev_qwen38_base.jsonl --compare runs/dev_dpo.jsonl --dev-ids eval/splits/dev_ids.txt --by-app
"""
from __future__ import annotations

import argparse
import inspect
import json
import os
import sys
from collections import Counter
from pathlib import Path
from typing import Any

# Default to the team's Qwen 3.8 4B model; still overridable via --model or QWEN_MODEL_PATH.
MODEL_NAME_OR_PATH = os.environ.get("QWEN_MODEL_PATH", "Ma7ee7/Qwen3.8_4B_Distilled")

DEFAULT_TRAIN_DATA = "optimize/dpo/dataset/dpo_train.jsonl"
DEFAULT_VAL_DATA = "optimize/dpo/dataset/dpo_val.jsonl"
DEFAULT_TOOL_CATALOG = "optimize/dpo/dataset/tool_specs_catalog.json"
DEFAULT_OUT_DIR = "checkpoints/planner_dpo_qwen38_lora"


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def load_tool_catalog(path: Path) -> dict[str, dict[str, Any]]:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def resolve_tools(row: dict[str, Any], catalog: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    """Reconstruct OpenAI function schemas from row['tools'] or row['tool_names'] + catalog."""
    if "tools" in row and row["tools"]:
        return row["tools"]
    return [catalog[n] for n in row.get("tool_names", []) if n in catalog]


def validate_dataset(train_rows: list[dict[str, Any]], val_rows: list[dict[str, Any]], catalog: dict[str, Any]) -> None:
    assert train_rows, "Training dataset is empty!"
    required_keys = {"id", "sample_id", "prompt", "chosen", "rejected"}
    train_sids = {r["sample_id"] for r in train_rows}
    val_sids = {r["sample_id"] for r in val_rows}
    overlap = train_sids & val_sids
    assert not overlap, f"Sample overlap between dpo_train and dpo_val: {sorted(overlap)[:5]}"

    for name, rows in [("train", train_rows), ("val", val_rows)]:
        for i, r in enumerate(rows):
            missing = required_keys - set(r.keys())
            assert not missing, f"{name}[{i}] missing keys: {missing}"
            assert isinstance(r["prompt"], list) and r["prompt"], f"{name}[{i}] prompt must be non-empty message list"
            assert isinstance(r["chosen"], str) and r["chosen"].strip(), f"{name}[{i}] chosen must be non-empty str"
            assert isinstance(r["rejected"], str) and r["rejected"].strip(), f"{name}[{i}] rejected must be non-empty str"
            assert r["chosen"] != r["rejected"], f"{name}[{i}] chosen == rejected"
            tools = resolve_tools(r, catalog)
            if r.get("tool_names"):
                assert len(tools) == len(r["tool_names"]), f"{name}[{i}] unresolved tool_names"


def wrap_reasoning_in_think(text: str) -> str:
    """Wrap pre-tool-call CoT lines inside `<think>...</think>` if not already present.

    Applied symmetrically to both chosen and rejected completions so DPO aligns with
    Qwen 3.8 Distilled's `<think>` format without spuriously rewarding tag absence.
    """
    if "</think>" in text:
        return text
    tc_idx = text.find("<tool_call>")
    if tc_idx != -1:
        cot = text[:tc_idx].strip()
        rest = text[tc_idx:].strip()
        return f"<think>\n{cot}\n</think>\n\n{rest}" if cot else text
    if "\n" in text:
        cot, reply = text.rsplit("\n", 1)
        if cot.strip() and reply.strip():
            return f"<think>\n{cot.strip()}\n</think>\n\n{reply.strip()}"
    return text


def format_row_for_dpo(
    row: dict[str, Any],
    catalog: dict[str, dict[str, Any]],
    tokenizer: Any,
    think_mode: str,
    max_prompt_tokens: int,
    wrap_think: bool = False,
) -> dict[str, str]:
    """Render (prompt, tools, chosen, rejected) using the selected Qwen model's chat template.

    If a sample exceeds `max_prompt_tokens`, drops the oldest user/assistant history turns
    while preserving the system prompt and latest user/tool turns (matching pipeline.py).
    """
    tools = resolve_tools(row, catalog)
    msgs = list(row["prompt"])
    kwargs: dict[str, Any] = {}
    if think_mode in ("on", "off"):
        kwargs["enable_thinking"] = think_mode == "on"

    def render_prompt(m_list: list[dict[str, Any]]) -> str:
        try:
            return tokenizer.apply_chat_template(
                m_list, tools=tools, add_generation_prompt=True, tokenize=False, **kwargs
            )
        except TypeError:
            return tokenizer.apply_chat_template(
                m_list, tools=tools, add_generation_prompt=True, tokenize=False
            )

    prompt_str = render_prompt(msgs)
    # Trim oldest history turns before the final user turn if prompt exceeds max_prompt_tokens
    if max_prompt_tokens > 0:
        n_tok = len(tokenizer.encode(prompt_str, add_special_tokens=False))
        while n_tok > max_prompt_tokens:
            # Find the second user turn after index 0 (system) so we never drop system or the active turn
            user_idxs = [idx for idx, m in enumerate(msgs) if m.get("role") == "user"]
            if len(user_idxs) <= 1:
                break
            first_u, second_u = user_idxs[0], user_idxs[1]
            msgs = msgs[:first_u] + msgs[second_u:]
            prompt_str = render_prompt(msgs)
            n_tok = len(tokenizer.encode(prompt_str, add_special_tokens=False))

    eos = tokenizer.eos_token or "<|im_end|>"
    chosen_raw = wrap_reasoning_in_think(row["chosen"]) if wrap_think else row["chosen"]
    rejected_raw = wrap_reasoning_in_think(row["rejected"]) if wrap_think else row["rejected"]
    chosen_str = chosen_raw if chosen_raw.endswith(eos) else chosen_raw + eos + "\n"
    rejected_str = rejected_raw if rejected_raw.endswith(eos) else rejected_raw + eos + "\n"
    return {"prompt": prompt_str, "chosen": chosen_str, "rejected": rejected_str}


def build_arg_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description="LoRA DPO fine-tuning for LifeMate Qwen 3.8 4B Planner")
    ap.add_argument(
        "--model",
        default=MODEL_NAME_OR_PATH,
        help="Qwen HF model ID or local checkpoint directory (default: Ma7ee7/Qwen3.8_4B_Distilled).",
    )
    ap.add_argument("--resume-from-lora", default="", help="Optional existing LoRA adapter path to initialize from.")
    ap.add_argument("--think", choices=["auto", "on", "off"], default="auto", help="Chat template enable_thinking mode.")
    ap.add_argument(
        "--wrap-think",
        "--wrap-chosen-think",
        dest="wrap_think",
        action="store_true",
        help="Symmetrically wrap BƯỚC 1/2/3 reasoning inside <think>...</think> on both chosen & rejected.",
    )

    # Pre-configured data & output paths
    ap.add_argument("--train-data", default=DEFAULT_TRAIN_DATA, help="Path to dpo_train.jsonl")
    ap.add_argument("--val-data", default=DEFAULT_VAL_DATA, help="Path to dpo_val.jsonl")
    ap.add_argument("--tool-catalog", default=DEFAULT_TOOL_CATALOG, help="Path to tool_specs_catalog.json")
    ap.add_argument("--out-dir", default=DEFAULT_OUT_DIR, help="Directory to save trained LoRA adapter")

    # DPO & LoRA hyperparameters
    ap.add_argument("--epochs", type=float, default=2.0)
    ap.add_argument("--lr", type=float, default=5e-6)
    ap.add_argument("--beta", type=float, default=0.1, help="DPO KL penalty beta")
    ap.add_argument("--bs", type=int, default=1, help="Per-device batch size")
    ap.add_argument("--grad-accum", type=int, default=16, help="Gradient accumulation steps (effective bs = bs * grad_accum)")
    ap.add_argument("--warmup-ratio", type=float, default=0.05)
    ap.add_argument("--weight-decay", type=float, default=0.01)
    ap.add_argument("--max-length", type=int, default=10240, help="Max total sequence tokens (prompt + completion)")
    ap.add_argument("--max-prompt-length", type=int, default=9216, help="Max prompt tokens before history trimming")
    ap.add_argument("--rank", type=int, default=16, help="LoRA rank r (lora_alpha = 2 * rank)")
    ap.add_argument("--lora-dropout", type=float, default=0.05)
    ap.add_argument("--load-in-4bit", action="store_true", help="Use QLoRA 4-bit NF4 quantization (for <=24GB VRAM)")
    ap.add_argument("--no-grad-ckpt", action="store_true", help="Disable gradient checkpointing")
    ap.add_argument("--precompute-ref-log-probs", action="store_true", help="Precompute reference log probs to save VRAM during steps")
    ap.add_argument("--limit", type=int, default=0, help="Limit training rows for quick smoke runs (0 = all)")
    ap.add_argument("--save-steps", type=int, default=100)
    ap.add_argument("--eval-steps", type=int, default=100)
    ap.add_argument("--logging-steps", type=int, default=10)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--dry-run", action="store_true", help="Validate data paths, schema, and args without loading model weights")
    return ap


def run_dry_check(args: argparse.Namespace, train_rows: list[dict[str, Any]], val_rows: list[dict[str, Any]], catalog: dict[str, Any]) -> None:
    print("[DRY-RUN] Validation passed.")
    print(f"  Model configured : {args.model or '<UNSET — pass --model <QWEN_MODEL_ID_OR_PATH> when running training>'}")
    print(f"  Train path       : {args.train_data} ({len(train_rows)} pairs, {len({r['sample_id'] for r in train_rows})} samples)")
    print(f"  Val path         : {args.val_data} ({len(val_rows)} pairs, {len({r['sample_id'] for r in val_rows})} samples)")
    print(f"  Tool catalog     : {args.tool_catalog} ({len(catalog)} tools)")
    print(f"  Output adapter   : {args.out_dir}")
    print(f"  Train by intent  : {dict(Counter(r.get('intent', '?') for r in train_rows))}")
    print(f"  Train neg classes: {dict(Counter(r.get('negative_class', '?') for r in train_rows))}")

    if args.model:
        from transformers import AutoTokenizer

        tok = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)
        sample_fmt = format_row_for_dpo(
            train_rows[0], catalog, tok, args.think, args.max_prompt_length, wrap_think=args.wrap_think
        )
        print(f"  Wrap <think>     : {args.wrap_think}")
        print(f"  Sample prompt chars={len(sample_fmt['prompt'])}, chosen chars={len(sample_fmt['chosen'])}, rejected chars={len(sample_fmt['rejected'])}")


def main() -> None:
    args = build_arg_parser().parse_args()
    train_path = Path(args.train_data)
    val_path = Path(args.val_data)
    catalog_path = Path(args.tool_catalog)

    for p in (train_path, val_path, catalog_path):
        if not p.exists():
            raise FileNotFoundError(f"Missing required DPO file: {p}. Run scripts/build_dpo_dataset.py first.")

    catalog = load_tool_catalog(catalog_path)
    train_rows = load_jsonl(train_path)
    if args.limit and args.limit > 0:
        train_rows = train_rows[: args.limit]
    val_rows = load_jsonl(val_path)
    validate_dataset(train_rows, val_rows, catalog)

    if args.dry_run:
        run_dry_check(args, train_rows, val_rows, catalog)
        return

    if not args.model:
        print(
            "ERROR: No Qwen model specified. Pass --model <HF_REPO_OR_LOCAL_PATH> "
            "or set QWEN_MODEL_PATH before launching DPO training.\n"
            "Example: python -m lifemate.planner.train_dpo --model Qwen/Qwen3-4B-Instruct-2507",
            file=sys.stderr,
        )
        sys.exit(2)

    # Heavy ML imports are deferred until actual training so --dry-run stays instant without GPU packages.
    import torch
    from datasets import Dataset
    from peft import LoraConfig, PeftModel, get_peft_model, prepare_model_for_kbit_training
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
    from trl import DPOConfig, DPOTrainer

    print(f"Loading tokenizer & model: {args.model}")
    tokenizer = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    use_bf16 = torch.cuda.is_available() and torch.cuda.is_bf16_supported()
    dtype = torch.bfloat16 if use_bf16 else (torch.float16 if torch.cuda.is_available() else torch.float32)

    model_kwargs: dict[str, Any] = {"torch_dtype": dtype, "trust_remote_code": True}
    if args.load_in_4bit:
        model_kwargs["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=dtype,
            bnb_4bit_use_double_quant=True,
        )
        model_kwargs["device_map"] = "auto"

    model = AutoModelForCausalLM.from_pretrained(args.model, **model_kwargs)
    if args.load_in_4bit:
        model = prepare_model_for_kbit_training(model)

    if not args.no_grad_ckpt:
        model.config.use_cache = False

    if args.resume_from_lora:
        model = PeftModel.from_pretrained(model, args.resume_from_lora, is_trainable=True)
        peft_config = None
    else:
        peft_config = LoraConfig(
            r=args.rank,
            lora_alpha=2 * args.rank,
            lora_dropout=args.lora_dropout,
            bias="none",
            task_type="CAUSAL_LM",
            target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        )
        if not args.load_in_4bit:
            model = get_peft_model(model, peft_config)
            model.print_trainable_parameters()
            peft_config = None  # already wrapped

    print("Formatting DPO train & val datasets with Qwen chat template + tool schemas...")
    train_formatted = [
        format_row_for_dpo(r, catalog, tokenizer, args.think, args.max_prompt_length, wrap_think=args.wrap_think)
        for r in train_rows
    ]
    val_formatted = [
        format_row_for_dpo(r, catalog, tokenizer, args.think, args.max_prompt_length, wrap_think=args.wrap_think)
        for r in val_rows
    ]

    train_ds = Dataset.from_list(train_formatted)
    val_ds = Dataset.from_list(val_formatted)

    # Build DPOConfig compatibly across TRL versions
    cfg_kwargs: dict[str, Any] = {
        "output_dir": args.out_dir,
        "num_train_epochs": args.epochs,
        "learning_rate": args.lr,
        "beta": args.beta,
        "per_device_train_batch_size": args.bs,
        "per_device_eval_batch_size": args.bs,
        "gradient_accumulation_steps": args.grad_accum,
        "warmup_ratio": args.warmup_ratio,
        "weight_decay": args.weight_decay,
        "lr_scheduler_type": "cosine",
        "logging_steps": args.logging_steps,
        "eval_strategy": "steps",
        "eval_steps": args.eval_steps,
        "save_strategy": "steps",
        "save_steps": args.save_steps,
        "save_total_limit": 2,
        "load_best_model_at_end": True,
        "metric_for_best_model": "eval_rewards/accuracies",
        "greater_is_better": True,
        "max_length": args.max_length,
        "max_prompt_length": args.max_prompt_length,
        "bf16": use_bf16,
        "fp16": torch.cuda.is_available() and not use_bf16,
        "gradient_checkpointing": not args.no_grad_ckpt,
        "precompute_ref_log_probs": args.precompute_ref_log_probs,
        "remove_unused_columns": False,
        "report_to": "none",
        "seed": args.seed,
    }
    valid_params = set(inspect.signature(DPOConfig.__init__).parameters.keys())
    if "warmup_ratio" not in valid_params and "warmup_steps" in valid_params:
        cfg_kwargs["warmup_steps"] = args.warmup_ratio
    filtered_cfg = {k: v for k, v in cfg_kwargs.items() if k in valid_params}
    dpo_args = DPOConfig(**filtered_cfg)

    trainer_sig = set(inspect.signature(DPOTrainer.__init__).parameters.keys())
    trainer_kwargs: dict[str, Any] = {
        "model": model,
        "ref_model": None,  # LoRA ref_model=None toggles adapter off cleanly without duplicating 4B weights in VRAM
        "args": dpo_args,
        "train_dataset": train_ds,
        "eval_dataset": val_ds,
        "peft_config": peft_config,
    }
    if "processing_class" in trainer_sig:
        trainer_kwargs["processing_class"] = tokenizer
    elif "tokenizer" in trainer_sig:
        trainer_kwargs["tokenizer"] = tokenizer

    trainer = DPOTrainer(**trainer_kwargs)
    trainer.train()

    out_path = Path(args.out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    trainer.save_model(str(out_path))
    tokenizer.save_pretrained(str(out_path))
    print(f"Saved DPO LoRA adapter & tokenizer -> {out_path}")


if __name__ == "__main__":
    main()
